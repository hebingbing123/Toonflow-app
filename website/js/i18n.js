  t(locale, key) {
    const pack = this.messages[locale] || this.messages[this.defaultLocale];
    return pack[key] ?? this.messages[this.defaultLocale][key] ?? key;
  },

  apply(locale) {
    const root = document.documentElement;
    root.lang = locale === "en" ? "en" : "zh-CN";

    document.title = this.t(locale, "meta.title");
    const metaDesc = document.querySelector('meta[name="description"]');
    if (metaDesc) metaDesc.setAttribute("content", this.t(locale, "meta.description"));

    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const value = this.t(locale, key);
      if (el.tagName === "IMG") {
        el.alt = value;
        return;
      }
      if (el.hasAttribute("data-i18n-html") || (value.includes("<") && value.includes(">"))) {
        el.innerHTML = value;
      } else {
        el.textContent = value;
      }
    });

    document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
      el.setAttribute("aria-label", this.t(locale, el.getAttribute("data-i18n-aria")));
    });

    document.querySelectorAll(".mockup-card[data-shot-index]").forEach((el) => {
      const n = el.getAttribute("data-shot-index");
      el.setAttribute("data-shot", `${this.t(locale, "mock.shot")} ${n.padStart(2, "0")}`);
    });

    const langBtn = document.getElementById("lang-toggle");
    if (langBtn) {
      langBtn.textContent = this.t(locale, "nav.lang");
      langBtn.setAttribute("aria-label", this.t(locale, "nav.langAria"));
    }

    document.querySelectorAll(".demo-modal__slide [data-caption-key]").forEach((cap) => {
      const key = cap.getAttribute("data-caption-key");
      if (key) cap.textContent = this.t(locale, key);
    });

    const closeBtn = document.getElementById("demo-modal-close");
    if (closeBtn) closeBtn.setAttribute("aria-label", this.t(locale, "demo.close"));

    try {
      localStorage.setItem("openflow-site-locale", locale);
    } catch (_) {
      /* ignore */
    }

    document.dispatchEvent(new CustomEvent("openflow:locale", { detail: { locale } }));
  },

  detect() {
    try {
      const saved = localStorage.getItem("openflow-site-locale");
      if (saved && this.locales.includes(saved)) return saved;
    } catch (_) {
      /* ignore */
    }
    const nav = (navigator.language || "").toLowerCase();
    return nav.startsWith("zh") ? "zh" : nav.startsWith("en") ? "en" : this.defaultLocale;
  },
